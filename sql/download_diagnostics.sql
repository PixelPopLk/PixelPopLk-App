-- PixelPopLK download diagnostics
-- Run this migration in Supabase SQL Editor before deploying the diagnostics PR.
-- Stores only allowlisted diagnostic metadata. Never store IP addresses, session tokens,
-- full user-agent strings, download URLs, or raw database error messages.

CREATE TABLE IF NOT EXISTS public.download_diagnostics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  diagnostic_id uuid NOT NULL,
  event text NOT NULL CHECK (event ~ '^[a-z][a-z0-9_]{1,63}$'),
  stage text NOT NULL CHECK (stage IN ('client', 'popup', 'start', 'return', 'claim', 'download')),
  outcome text NOT NULL CHECK (outcome IN ('info', 'success', 'failure')),
  subtitle_id bigint,
  variant text NOT NULL CHECK (variant IN ('direct', 'telegram')),
  browser_family text NOT NULL DEFAULT 'other'
    CHECK (browser_family IN ('chrome', 'samsung', 'firefox', 'safari', 'edge', 'other')),
  browser_context text NOT NULL DEFAULT 'browser'
    CHECK (browser_context IN ('telegram', 'facebook', 'instagram', 'browser', 'other')),
  http_status integer CHECK (http_status IS NULL OR (http_status BETWEEN 100 AND 599)),
  error_code text CHECK (error_code IS NULL OR error_code ~ '^[a-z][a-z0-9_]{1,63}$'),
  elapsed_ms integer CHECK (elapsed_ms IS NULL OR elapsed_ms BETWEEN 0 AND 600000),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS download_diagnostics_created_at_idx
  ON public.download_diagnostics (created_at DESC);
CREATE INDEX IF NOT EXISTS download_diagnostics_diagnostic_id_idx
  ON public.download_diagnostics (diagnostic_id, created_at ASC);
CREATE INDEX IF NOT EXISTS download_diagnostics_failure_idx
  ON public.download_diagnostics (created_at DESC)
  WHERE outcome = 'failure';

ALTER TABLE public.download_diagnostics ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.download_diagnostics FROM PUBLIC, anon, authenticated;
GRANT INSERT, SELECT ON TABLE public.download_diagnostics TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.download_diagnostics_id_seq TO service_role;

COMMENT ON TABLE public.download_diagnostics IS
  'Allowlisted download-flow diagnostics; no IPs, tokens, raw user agents, or download URLs.';
